const warnedMissing = new Set<string>();
let validated = false;

export function normalizeLocale(value: string | null | undefined): Locale {
  if (value === 'ru') return 'ru';
  return 'en';
}

export function translate(
  locale: Locale,
  key: string,
  params?: Record<string, string | number>,
): string {
  let text = translations[locale]?.[key] ?? translations.en[key];
  if (!text) {
    if (process.env.NODE_ENV !== 'production') {
      const id = `${locale}:${key}`;
      if (!warnedMissing.has(id)) {
        warnedMissing.add(id);
        console.warn(`[i18n] Missing translation key: ${id}`);
      }
    }
    text = key;
  }

  if (!params) return text;

  let result = text;
  for (const [paramKey, paramValue] of Object.entries(params)) {
    result = result.replaceAll(`{${paramKey}}`, String(paramValue));
  }
  return result;
}

export function getTranslator(locale: Locale) {
  return (key: string, params?: Record<string, string | number>) =>
    translate(locale, key, params);
}

export function validateTranslationCoverage(): void {
  if (validated) return;
  validated = true;

  const baseKeys = new Set(Object.keys(translations.en));
  for (const [locale, dict] of Object.entries(translations) as Array<
    [Locale, Record<string, string>]
  >) {
    for (const key of baseKeys) {
      if (!(key in dict)) {
        console.warn(`[i18n] Missing key in ${locale}: ${key}`);
      }
    }
  }
}
